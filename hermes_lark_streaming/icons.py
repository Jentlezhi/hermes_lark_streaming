"""卡片符号表 — 出现在飞书卡片上的每一个 emoji 的唯一定义处.

**为什么要集中**：这些符号原先散在 5 个文件的 31 个 f-string 里，换一个符号要
全项目搜一遍，漏一处就出现同一语义两种符号。集中之后它们是一张可配置的表，
也终于有地方写清楚「这个符号出现在哪、什么时候出现」。

**怎么配**：在 Hermes 的 ``config.yaml`` 里写

.. code-block:: yaml

    streaming:
      icons:
        reasoning: "🤔"      # 只覆盖想改的，其余仍用默认
        subagent: ""         # 空字符串 = 不显示这个符号

配置走 :class:`~hermes_lark_streaming.config.Config` 的 5 秒 TTL 缓存，改完发下
一条消息即生效，不必重启 gateway。

**取值口径**：只有「非空字符串」才算有效覆盖，其余一律回落默认。这样配错类型
（写成数字、写成列表）不会让渲染崩掉，也不会显示出 ``None`` 之类的字面量。
空字符串是唯一的例外——那是用户明确表达「这里不要符号」。

**放在包顶层而不是 ``render/`` 下**：这张表要被三层同时用到——``render`` 拼卡片
元素、``core.Turn`` 拼会话列表预览、``bridge.subagent`` 拼子任务提示。放进
``render/`` 会让 ``core`` 反向依赖渲染层，破坏单向依赖；符号表本质是常量，与
``config`` 同级才对。

**不在本表内的符号**：``events/normalize.py`` 里的 💾🧠📝 是**分类正则**的一部分，
用来识别 Hermes 的记忆更新类消息，不是展示用的，改它会改变判定行为；CLI 输出的
✔✘（``__main__.py`` / ``selfheal/healer.py``）显示在终端而非卡片，与飞书渲染无关。
两者都不参与本表。
"""

from __future__ import annotations

from typing import Any, Final

