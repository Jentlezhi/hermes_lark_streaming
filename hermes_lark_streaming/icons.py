#: 符号表类型别名。用 ``None`` 表示「调用方没传，用默认表」——渲染层的函数因此
#: 可以不强制每个调用点都传，漏传只是退回默认符号，不会抛错也不会显示占位符。
IconSet = dict[str, str] | None


def get(icons: IconSet, key: str) -> str:
    """取一个符号；缺失、类型不符、未配置都回落默认表.

    键不在默认表里时返回空字符串而不是抛错：渲染路径上一个拼错的键不该让整张卡片
    发不出去。这与 :func:`.render.i18n.t` 的容错口径一致。
    """
    if icons is not None:
        value = icons.get(key)
        if isinstance(value, str):
            return value
    return DEFAULT_ICONS.get(key, "")


def resolve(cfg: Any) -> dict[str, str]:
    """按配置解析出完整符号表.

    先复制默认表，再用配置里的有效项覆盖——这样即使用户只配了一个键，其余仍然
    齐全，调用方拿到的永远是完整表，不必自己兜底。

    ``cfg`` 读失败时返回默认表：符号是纯展示，配置读不出来不该影响卡片能不能发。
    """
    merged = dict(DEFAULT_ICONS)
    try:
        overrides = cfg.icons
    except Exception:
        return merged
    if not isinstance(overrides, dict):
        return merged
    for key, value in overrides.items():
        # 只认已知键：未知键要么是拼错，要么是旧版本残留，静默忽略比塞进表里安全
        if key in merged and isinstance(value, str):
            merged[key] = value
    return merged


def with_space(icons: IconSet, key: str) -> str:
    """取符号并补一个尾随空格；符号被配成空字符串时连空格一起省掉.

    专门给 ``f"{icon} 文案"`` 这类拼接用。用户把某个符号配成 `""` 是想让它彻底
    消失，若仍留一个前导空格，文案就会诡异地缩进一格。
    """
    value = get(icons, key)
    return f"{value} " if value else ""
